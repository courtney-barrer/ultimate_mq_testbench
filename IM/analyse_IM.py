def data_root():
    for start in (Path(__file__).resolve().parent,Path.cwd().resolve()):
        for parent in (start,*start.parents):
            if (parent/'.git').exists():return parent/'data'
    raise ValueError('No Git repository found; supply --output DIRECTORY')


def tsvd(j,rcond):
    u,s,vt=np.linalg.svd(j,full_matrices=False)
    keep=s>rcond*s[0] if s[0]>0 else np.zeros(len(s),bool)
    inv=np.zeros_like(s);inv[keep]=1/s[keep]
    return (vt.T*inv)@u.T,s,keep


def noise_estimate(f,amps,modeids):
    """Approximate independent-state SEM; combine shared middle-flat weight once.
    Does not include correlated dark/background errors or inter-frame drift.
    """
    rows=f['SLOPE_ROWS'].data;spot=rows['SPOT_ID'].astype(int)
    # SPOT_ID values are row indices in SLMIM v1 generated by build_IM.py.
    axis=np.array([0 if str(v).strip()=='x' else 1 for v in rows['AXIS']])
    sem=f['CENT_SEM'].data[:,spot,axis];states=f['STATES'].data
    variance=np.zeros((len(amps),len(rows),len(modeids)))
    for ai,amp in enumerate(amps):
        for mi,mode in enumerate(modeids):
            ids=[]
            for kind in ('flat_before','plus','flat_middle','minus','flat_after'):
                ix=np.flatnonzero((states['AMP_IDX']==ai)&(states['MODE_ID']==mode)&(states['KIND']==kind))
                if len(ix)!=1:raise ValueError('Expected exactly one five-state sequence per mode/amplitude')
                ids.append(ix[0])
            t=np.array([f[f'IMAGE{int(states[i]["STATE"]):05d}'].header['HOSTNS'] for i in ids],dtype=np.float64)
            if not np.all(np.diff(t)>0):raise ValueError('Non-increasing acquisition timestamps')
            wp=(t[1]-t[0])/(t[2]-t[0]);wm=(t[3]-t[2])/(t[4]-t[2])
            weight=np.array([-(1-wp),1,1-wm-wp,-1,-wm])/(2*amp)
            variance[ai,:,mi]=np.sum((sem[ids]*weight[:,None])**2,axis=0)
    return variance


def run(a):
    out=a.output or data_root()/('IM_analysis_'+time.strftime('%Y%m%d_%H%M%S'))
    with fits.open(a.input,memmap=True) as f:
        h=f[0].header.copy()
        if h.get('SCHEMA')!='SLMIM' or not h.get('COMPLETE'):raise ValueError('Need a completed SLMIM FITS')
        j=np.array(f['IM'].data,dtype=float);half=np.array(f['HALFDIFF'].data,dtype=float)
        amps=np.array(f['AMPLITUDES'].data['AMPLITUDE'],dtype=float)
        modes=np.array(f['IM_MODES'].data['MODE_ID'],dtype=int)
        if not np.isfinite(j).all() or j.shape!=(len(amps),len(f['SLOPE_ROWS'].data),len(modes)):raise ValueError('Invalid matrix shape/data')
        np.testing.assert_allclose(half,j*amps[:,None,None],rtol=2e-6,atol=1e-8)
        if a.cal_amplitude is None:cal=int(np.argmax(amps))
        else:
            match=np.flatnonzero(np.isclose(amps,a.cal_amplitude,rtol=0,atol=1e-8))
            if len(match)!=1:raise ValueError(f'Calibration amplitude must be one of {amps}')
            cal=int(match[0])
        rec=[];singular=[];ranks=[]
        for matrix in j:
            r,s,keep=tsvd(matrix,a.rcond);rec.append(r);singular.append(s);ranks.append(int(keep.sum()))
        rec=np.array(rec);singular=np.array(singular)
        # G[c,t,recovered_mode,injected_mode]. Diagonal blocks are self fits only.
        gains=np.array([[r@jt for jt in j] for r in rec])
        recovered=gains*amps[None,:,None,None]
        residual=np.array([[np.linalg.norm(jt-jc@(r@jt),axis=0)/np.maximum(np.linalg.norm(jt,axis=0),1e-30)
            for jt in j] for jc,r in zip(j,rec)])
        var=noise_estimate(f,amps,modes)
        noise_ratio=np.sqrt(var.sum(axis=1))/np.maximum(np.linalg.norm(j,axis=1),1e-30)
        rows=f['SLOPE_ROWS'].copy();spots=f['SPOTS'].copy();valid=f['VALID'].copy()
        ref=f['SPOTS'].data['REF_FLUX'];good=f['VALID'].data.astype(bool)
        fluxratio=np.median(f['FLUX'].data[:,good]/ref[good],axis=1)
        states=f['STATES'].data.copy()
        flat=np.array([str(v).startswith('flat') for v in states['KIND']])
        # The raw flat slope drift is relative to initial reference (no local drift removal).
        flat_slopes=np.array(f['SLOPES'].data[flat][:,good,:],float)
        drift=np.sqrt(np.mean(flat_slopes**2,axis=(1,2)))
        modes_table=f['IM_MODES'].copy();amp_table=f['AMPLITUDES'].copy()
    out.mkdir(parents=True,exist_ok=False)
    lines=[f'Input: {a.input.resolve()}',f'Basis SHA256: {h["BASISHA"]}',
           f'Registration validated: {h["REGVALID"]}',f'Modes: {modes.tolist()}; lenslets: {int(good.sum())}',
           f'TSVD rcond={a.rcond:g}; selected calibration amplitude={amps[cal]:g} grey RMS',
           'Cross-amplitude tests share the same run, dark and spot registration; not independent validation.',
           'Self-fit R@IM checks algebra only. Unmodelled wavefront modes cannot be reconstructed.',
           'SEM noise estimate excludes correlated errors/drift and is not a complete uncertainty budget.']
    for i,amp in enumerate(amps):
        condition=singular[i,0]/singular[i,-1] if singular[i,-1]>0 else np.inf
        lines += [f'Amplitude {amp:g}: retained rank={ranks[i]}/{len(modes)}, condition={condition:.4g}',
                  f'  Estimated centroid-noise norm / measured column norm: {noise_ratio[i].round(4).tolist()}']
    for i in range(len(amps)):
        for k in range(i+1,len(amps)):
            cosine=np.sum(j[i]*j[k],axis=0)/(np.linalg.norm(j[i],axis=0)*np.linalg.norm(j[k],axis=0))
            lines.append(f'Column cosine similarity, {amps[i]:g} vs {amps[k]:g}: {cosine.round(4).tolist()}')
    for test,amp in enumerate(amps):
        if test==cal:continue
        lines += [f'Calibrate at {amps[cal]:g}, test at {amp:g}:',
                  '  Recovered coefficient columns (one injected mode per column), grey RMS:',
                  np.array2string(recovered[cal,test],precision=4),
                  f'  Unexplained slope-vector norm fractions: {residual[cal,test].round(4).tolist()}']
    if len(amps)==1:lines.append('Only one amplitude: no cross-amplitude validation possible.')
    lines.append(f'Flat-state median lenslet flux ratio range: {fluxratio[flat].min():.4f} .. {fluxratio[flat].max():.4f}')
    lines.append(f'Flat centroid RMS drift range: {drift.min():.5f} .. {drift.max():.5f} px')
    (out/'report.txt').write_text('\n'.join(lines)+'\n');print('\n'.join(lines))
    digest=hashlib.sha256()
    with a.input.open('rb') as stream:
        for chunk in iter(lambda:stream.read(1024*1024),b''):digest.update(chunk)
    rh=fits.Header(dict(SCHEMA='SLMRECON',SCHEMAV=1,COMPLETE=True,BUNIT='grey/pixel',
        CALAMP=float(amps[cal]),RCOND=a.rcond,RANK=ranks[cal],BASISHA=h['BASISHA'],
        IMSHA=digest.hexdigest(),IMFILE=a.input.name,BASISTYP=h['BASISTYP'],REGVALID=h['REGVALID'],
        SLOPORD=h['SLOPORD'],AMPUNIT='grey RMS',NMODES=len(modes)))
    for key in ('CAMX','CAMY','CAMW','CAMH','CROPX','CROPY','EXPTIME','HALF','BASELINE'):rh[key]=h[key]
    rh['COMMENT']='Primary R[mode,slope]: coefficient = R @ reference-subtracted slope vector.'
    rh['COMMENT']='Use saved SLOPE_ROWS and identical centroid estimator/ROI; no command negation applied.'
    rh['COMMENT']='Offline cross-amplitude consistency only; not independent validation or phase calibration.'
    fits.HDUList([fits.PrimaryHDU(rec[cal],rh),fits.ImageHDU(rec,name='RECON_ALL'),
        fits.ImageHDU(j,name='IM'),fits.ImageHDU(singular,name='SINGULAR'),
        fits.ImageHDU(np.array(ranks),name='RANKS'),fits.ImageHDU(gains,name='GAIN'),
        fits.ImageHDU(recovered,name='RECOVERED'),fits.ImageHDU(residual,name='RESIDUAL'),
        fits.ImageHDU(var,name='IM_VAR_APPROX'),rows,spots,valid,modes_table,amp_table]).writeto(out/'reconstructor.fits',checksum=True)
    fig,axes=plt.subplots(1,3,figsize=(15,4))
    for i,amp in enumerate(amps):
        axes[0].semilogy(np.arange(1,len(singular[i])+1),singular[i],'o-',label=f'{amp:g} grey')
        axes[1].plot(modes,np.linalg.norm(j[i],axis=0),'o-',label=f'{amp:g} grey')
    axes[0].set(xlabel='Singular-value index',ylabel='pixel / grey',title='IM singular values');axes[0].legend()
    axes[1].set(xlabel='Basis mode ID',ylabel='Column norm [pixel/grey]',title='Amplitude-normalised response');axes[1].legend()
    axes[2].plot(fluxratio);axes[2].set(xlabel='State index',ylabel='Median flux / reference',title='Intensity stability')
    fig.tight_layout();fig.savefig(out/'overview.png',dpi=150);plt.close(fig)
    fig,axes=plt.subplots(len(amps),len(amps),figsize=(5*len(amps),4*len(amps)),squeeze=False)
    for c in range(len(amps)):
        for t in range(len(amps)):
            ax=axes[c,t];im=ax.imshow(gains[c,t],vmin=-1,vmax=1,cmap='RdBu_r')
            ax.set(title=f'Cal {amps[c]:g}, test {amps[t]:g}'+(' (self fit)' if c==t else ''),xlabel='Injected mode',ylabel='Recovered mode',xticks=range(len(modes)),yticks=range(len(modes)))
            ax.set_xticklabels(modes);ax.set_yticklabels(modes)
            if len(modes)<=12:
                for (y,x),v in np.ndenumerate(gains[c,t]):ax.text(x,y,f'{v:.2f}',ha='center',va='center',color='black',bbox=dict(facecolor='white',alpha=.7,edgecolor='none'))
            fig.colorbar(im,ax=ax,label='Recovered / injected coefficient')
    fig.tight_layout();fig.savefig(out/'cross_amplitude.png',dpi=140);plt.close(fig)
    print(f'Output: {out.resolve()}')
    return out



# Self-contained copy of build_IM acquisition/centroid helpers; no sibling imports.
HOST, PORT, DEVICE, STREAM = "127.0.0.1", 18010, "dcam0", "dcam0_data"
SENSOR_WH = (2304,2304)

def command(cmd, timeout=30.):
    deadline = time.monotonic() + timeout
    data = bytearray()
    with socket.create_connection((HOST, PORT), timeout=min(5.,timeout)) as sock:
        sock.sendall(f'{DEVICE} {cmd}\r'.encode('ascii'))
        while b'\r' not in data:
            left = deadline - time.monotonic()
            if left <= 0: raise TimeoutError(f'{cmd}: missing reply terminator')
            sock.settimeout(left)
            part = sock.recv(4096)
            if not part: raise RuntimeError(f'{cmd}: connection closed before reply terminator')
            data.extend(part)
            if len(data) > 65536: raise RuntimeError('Oversized reply')
    reply = bytes(data).split(b'\r', 1)[0].decode(errors='replace').strip()
    if any(line.lstrip().startswith('Error:') for line in reply.splitlines()):
        raise RuntimeError(f'{cmd}: {reply}')
    return reply

def status(text):
    f = dict(re.findall(r'^\s*([\w ]+?)\s*:\s*\[\s*(.*?)\s*\]', text, re.M))
    w, h = map(int, re.fullmatch(r'(\d+)x(\d+)', f['Image size']).groups())
    ox, oy = map(int, re.findall(r'-?\d+', f['Offset']))
    return dict(roi=[(SENSOR_WH[0]-w)//2+ox, (SENSOR_WH[1]-h)//2+oy, w, h],
                exposure=float(f['Exptime']), busy=f['Capture'].startswith('BUSY'), raw=text)

class Camera:
    """Attach to the running stream; never start, stop, crop or change exposure."""
    def __init__(self):
        import ImageStreamIOWrap
        self.original = status(command('st'))
        if not self.original['busy']:
            raise RuntimeError('Start the camera in the normal GUI before running this script.')
        self.image = ImageStreamIOWrap.Image()
        rc = self.image.open(STREAM)
        if rc not in (None, 0):
            self.image.close()
            raise RuntimeError(f'Cannot open {STREAM}: {rc}')
        self.last = self.state()[0]
        self.exposure = self.original['exposure']

    def state(self):
        md = self.image.md
        if not hasattr(md, 'cnt0'): md = md[0]
        return int(md.cnt0), bool(md.write)

    def frame(self):
        end = time.monotonic() + max(10., 3*self.exposure+2)
        while time.monotonic() < end:
            before, writing = self.state()
            if before < self.last: raise RuntimeError('Camera frame counter reset')
            if before > self.last and not writing:
                im = np.array(self.image, copy=True).T
                after, writing = self.state()
                if after == before and not writing:
                    if im.shape != tuple(self.original['roi'][2:][::-1]):
                        raise RuntimeError('Unexpected camera shape after XY to YX transpose')
                    self.last = after
                    return im, after, time.time_ns()
            time.sleep(.001)
        raise TimeoutError(f'No fresh stable camera frame: last accepted={self.last}, '
                           f'last observed={before}, write={writing}; stream={STREAM}')

    def check(self):
        s = status(command('st'))
        if not s['busy'] or s['roi'] != self.original['roi'] or abs(s['exposure']-self.exposure)>1.1e-5:
            raise RuntimeError('Camera exposure/ROI/capture changed during the test')

    def close(self):
        self.image.close()

class Bench:
    def __init__(self, args):
        self.cam = self.slm = None
        self.args = args
        try:
            from slmdisplay import SLM
            self.cam = Camera()
            screen = int(args.screen) if args.screen.lstrip('-').isdigit() else args.screen
            self.slm = SLM(screen=screen)
            self.shape = (self.slm.height, self.slm.width)
            if self.shape != (args.ny,args.nx):
                raise ValueError(f'SLM shape {self.shape} differs from requested Ny,Nx={(args.ny,args.nx)}')
            self.flat = np.full(self.shape, args.baseline, np.uint8)
            self.show(self.flat)
        except BaseException:
            self.close(); raise

    def show(self, pattern):
        seq = self.slm.show(pattern, wait=True)
        # Vsync acknowledgement is not exposure synchronisation or LC settling.
        time.sleep(self.args.settle + 2*self.cam.exposure)
        count, _ = self.cam.state()
        if count < self.cam.last: raise RuntimeError('Camera counter reset during settling')
        self.cam.last = count
        for _ in range(self.args.flush): self.cam.frame()
        return seq

    def restore_flat(self):
        # Restoring the SLM is independent of whether the camera is still alive.
        return self.slm.show(self.flat, wait=True)

    def close(self):
        # Report cleanup failures without replacing the acquisition traceback.
        if self.slm is not None:
            slm = self.slm
            try:
                if hasattr(self, 'flat'): self.restore_flat()
            except Exception as exc: print(f'Cleanup warning: flat display: {exc}', flush=True)
            try: slm.close()
            except FileNotFoundError as exc:
                if str(exc.filename or '').startswith('/psm_'):
                    print('Cleanup warning: SLM buffer already unlinked; apply the included slmdisplay patch.',flush=True)
                else: print(f'Cleanup warning: SLM close: {exc}',flush=True)
            except Exception as exc: print(f'Cleanup warning: SLM close: {exc}',flush=True)
            self.slm = None
        if self.cam is not None:
            try: self.cam.close()
            except Exception as exc: print(f'Cleanup warning: camera detach: {exc}',flush=True)
            self.cam = None

def measure(image,variance,sat,centres,half):
    """Fixed-window signed centre of gravity, local border-median background.
    Negative background-subtracted values are retained. No frame-dependent mask.
    SEM is approximate propagated variance of the averaged image, not jitter.
    """
    yy,xx=np.mgrid[-half:half+1,-half:half+1]
    border=np.maximum(abs(xx),abs(yy))>=half-1
    patches=image[centres[:,1,None,None]+yy,centres[:,0,None,None]+xx].astype(float)
    v=variance[centres[:,1,None,None]+yy,centres[:,0,None,None]+xx].astype(float)
    bad=sat[centres[:,1,None,None]+yy,centres[:,0,None,None]+xx].any(axis=(1,2))
    bg=np.median(patches[:,border],axis=1);z=patches-bg[:,None,None];flux=z.sum(axis=(1,2))
    # Median-background variance approximation for locally Gaussian independent noise.
    vbg=np.pi/2*np.median(v[:,border],axis=1)/border.sum()
    fvar=v.sum(axis=(1,2))+z.shape[1]**4*vbg
    with np.errstate(divide='ignore',invalid='ignore'):
        cx=(z*xx).sum(axis=(1,2))/flux;cy=(z*yy).sum(axis=(1,2))/flux
        errors=[]
        for coord,c in ((xx,cx),(yy,cy)):
            weight=coord[None]-c[:,None,None]
            errors.append(np.sqrt((v*weight**2).sum(axis=(1,2))+vbg*weight.sum(axis=(1,2))**2)/flux)
        snr=flux/np.sqrt(np.maximum(fvar,1e-12))
    good=(~bad)&np.isfinite(cx)&np.isfinite(cy)&(flux>0)&(snr>=10)&(np.maximum(abs(cx),abs(cy))<.6*half)
    xy=np.column_stack((cx,cy))+centres
    sem=np.column_stack(errors)
    return xy,sem,good,flux,snr,bg

def table(name, columns):
    return fits.BinTableHDU.from_columns([fits.Column(name=k,format=fmt,array=v)
        for k,fmt,v in columns],name=name)

def append(path, hdus):
    # Each completed acquisition survives a later timeout. COMPLETE stays false.
    with fits.open(path,mode='append',memmap=False) as f:
        for h in hdus:
            h.add_checksum();f.append(h)
        f.flush(output_verify='exception')

def capture(bench,a,pattern,path,index,kind,mode=-1,amp=0.):
    bench.cam.check();seq=bench.show(pattern)
    stamps=[];counts=[]
    for i in range(a.frames_per_probe):
        im,c,t=bench.cam.frame()
        if a.demo and kind=='dark':im=100+bench.rng.normal(0,2,im.shape)
        if a.roi:
            x,y,w,h=a.roi
            if x<0 or y<0 or x+w>im.shape[1] or y+h>im.shape[0]:raise ValueError('Software ROI outside camera frame')
            im=im[y:y+h,x:x+w]
        im=im.astype(float)
        if not np.isfinite(im).all():raise ValueError('Nonfinite image')
        if i==0:mean=np.zeros_like(im);m2=mean.copy();sat=np.zeros(im.shape,bool)
        delta=im-mean;mean+=delta/(i+1);m2+=delta*(im-mean);sat|=im>=a.saturation
        stamps.append(t);counts.append(c)
    if np.any(np.diff(counts)<=0):raise RuntimeError('Repeated frame counters')
    var=m2/(a.frames_per_probe-1)/a.frames_per_probe
    h=fits.Header(dict(STATE=index,KIND=kind,COMBOID=mode,AMPL=amp,NFRAMES=a.frames_per_probe,
        EXPTIME=bench.cam.exposure,HOSTNS=int(np.mean(stamps)),SLMSEQ=int(seq or 0),BUNIT='ADU',
        CMDHASH=hashlib.sha256(pattern.tobytes()).hexdigest()))
    append(path,[fits.ImageHDU(mean.astype('float32'),h,name=f'IMAGE{index:05d}'),
        fits.ImageHDU(var.astype('float32'),fits.Header({'BUNIT':'ADU^2'}),name=f'VAR{index:05d}'),
        fits.ImageHDU(sat.astype('uint8'),name=f'SAT{index:05d}'),
        table(f'TIME{index:05d}',[('COUNTER','K',counts),('HOST_NS','K',stamps)])])
    print(f'{index:05d} {kind}: combination {mode}, amplitude {amp:g}; max mean {mean.max():.0f} ADU',flush=True)
    return dict(image=mean,var=var,sat=sat,time=float(np.mean(stamps)),index=index)


def file_hash(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()


def combinations(a,modes):
    if a.probe_coefficients:
        c=np.array(a.probe_coefficients,float)
        if c.shape[1]!=len(modes):raise ValueError('--probe-coefficients needs one value per IM mode, in IM_MODES order')
    else:
        selected=modes if a.probe_modes is None else np.array(a.probe_modes)
        if len(set(selected))!=len(selected) or not set(selected)<=set(modes):raise ValueError('--probe-modes must be distinct mode IDs calibrated in this IM')
        c=np.zeros((a.probe_count,len(modes)))
        rng=np.random.default_rng(a.probe_seed)
        v=rng.normal(size=(a.probe_count,len(selected)))
        v*=a.probe_rms/np.linalg.norm(v,axis=1)[:,None]
        for j,mode in enumerate(selected):c[:,np.flatnonzero(modes==mode)[0]]=v[:,j]
    if not np.isfinite(c).all() or np.any(np.linalg.norm(c,axis=1)==0):raise ValueError('Probe coefficients must be finite and nonzero')
    return c


def mode_map(basis,modes,coefficients):
    result=np.zeros(basis[0].data.shape[1:],float)
    for mode,c in zip(modes,coefficients):
        if c:result+=c*np.asarray(basis[0].data[mode],float)
    return result


def command_map(h,z,sign):
    crop=h['BASELINE']+sign*np.rint(z)
    if not np.isfinite(crop).all() or crop.min()<0 or crop.max()>255:raise ValueError('Combined probe exceeds 8-bit headroom; lower --probe-rms or coefficients')
    cmd=np.full((h['SLMNY'],h['SLMNX']),h['BASELINE'],np.uint8)
    cmd[h['Y0']:h['Y1'],h['X0']:h['X1']]=crop.astype(np.uint8)
    return cmd


def plot_probes(path,applied,reconstructed,mask,header):
    n=len(applied);fig,axes=plt.subplots(n,3,figsize=(13,3.8*n),squeeze=False,layout='constrained')
    for i,(truth,estimate) in enumerate(zip(applied,reconstructed)):
        diff=truth-estimate
        limit=max(float(np.max(np.abs(v[mask]))) for v in (truth,estimate,diff)) or 1.
        for j,(z,title) in enumerate(zip((truth,estimate,diff),('Applied probe','Reconstructed','Applied − reconstructed'))):
            im=axes[i,j].imshow(np.where(mask,z,np.nan),origin='upper',cmap='RdBu_r',vmin=-limit,vmax=limit,
                extent=[header['X0']-.5,header['X1']-.5,header['Y1']-.5,header['Y0']-.5])
            axes[i,j].set(title=f'Probe {i+1}: {title}\npupil RMS {np.sqrt(np.mean(z[mask]**2)):.3g} grey',xlabel='SLM x',ylabel='SLM y')
        fig.colorbar(im,ax=list(axes[i]),label='SLM grey displacement from baseline',shrink=.85)
    fig.savefig(path,dpi=160);plt.close(fig)


def validate_live(a,out):
    """Independent fresh paired acquisition with fixed calibrated lenslet windows."""
    if a.basis is None:raise ValueError('--probe-validation requires --basis basis.fits')
    with fits.open(out/'reconstructor.fits',memmap=True) as rf, fits.open(a.input,memmap=True) as old, fits.open(a.basis,memmap=True) as basis:
        rh=rf[0].header;bh=basis[0].header
        if bh.get('SCHEMA')!='SLMBASIS' or bh.get('SCHEMAV')!=1 or not bh.get('COMPLETE'):raise ValueError('Need complete SLMBASIS v1 FITS')
        if file_hash(a.basis)!=rh['BASISHA']:raise ValueError('Basis SHA256 differs from calibration')
        if not rh['REGVALID'] and not a.allow_unvalidated:raise ValueError('Registration unvalidated: explicitly add --allow-unvalidated for exploratory probes')
